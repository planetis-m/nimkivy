## Typed Kivy properties and events: the `properties:` block.
##
## .. code-block:: nim
##   properties:
##     type
##       Widget* = ref object of RootObj
##         x* {.prop.}: float = 0.0                     # Numeric
##         width* {.prop.}: float = 100.0
##         pos* {.refs: (x, y).}: (float, float)        # ReferenceList
##         right* {.alias: (getRight, setRight), deps: (x, width), cache.}: float
##         opacity* {.bounds: 0.0 .. 1.0, handler.}: float = 1.0
##         padding* {.varlist: 4.}: array[4, float]     # VariableList
##         color* {.color.}: Rgba = [1.0, 1, 1, 1]      # Color
##         press* {.event.}: proc ()
##       Label* {.defaults: (opacity: 0.5).} = ref object of Widget
##
##     proc getRight(w: Widget): float = w.x + w.width
##     proc setRight(w: Widget; v: float): bool =
##       w.x = v - w.width
##       result = false
##
## A field's pragma says its kind:
##
## - `prop`: a property; Kivy's Numeric, String, Boolean, Object, List and
##   Option properties are all this, the Nim type says which (`Opt[T]` for
##   `allownone`, an enum for an option; a `ref` compares by identity);
## - `bounds: lo .. hi`: a property whose values must lie in `lo .. hi`; a
##   value outside stops the program, where Kivy raises ValueError;
## - `refs: (a, b)`: a ReferenceList of properties of the type or its bases;
## - `alias: (get, set)` or `alias: get` (read-only), with `deps: (a, b)`
##   (Kivy's `bind`), `cache` and `eager` (Kivy's `watch_before_use`);
## - `color`: a property of type `Rgba` that can also be set from 3 numbers
##   (alpha 1);
## - `varlist: 4` or `varlist: 2`: an `array[4, float]` or `array[2, float]`
##   that can also be set from 1 or 2 numbers;
## - `always`, with another kind: dispatch even when the value is unchanged
##   (Kivy's `force_dispatch`);
## - `handler`, with another kind: the class's `on_<prop>`, the base method
##   `on<Prop>Changed`, bound first on every instance;
## - `event`, with the type `proc (args)`: an event;
## - no pragma: a plain field.
##
## `{.defaults: (name: value, ...).}` on a type overrides inherited defaults.
## Other statements in the block (the types' procs and methods) are copied
## after the generated code.
##
## Generated for each property `p: T` of `Owner`: `p(w): T`, `` `p=`(w; v) ``
## (dispatches only on a change), `bindP(w; cb): Binding` (`cb` is a
## `proc (v: T) {.closure.}`), `unbindP(w; b)`, `dispatchP(w)` (dispatches the
## current value) and `initP(w; v)` (sets without a dispatch; not for refs and
## aliases). For each event `e: proc (args)`: `bindE(w; cb)` (`cb` is a
## `proc (args): bool {.closure.}`), `unbindE(w; b)`, `dispatchE(w; args):
## bool` and the default handler, the base method `onE(w; args): bool`. For
## each type: `initProps(w)`, which its constructor calls once.
##
## For each settable property of type `float`, `(float, float)`,
## `array[N, float]` or `seq[float]` as written (an alias of these is not
## recognised), and each `color` and `varlist`, an Animation track:
## `pTo(Owner, v): Track` (moves `p` to `v`) and `pKey(Owner): TrackKey`
## (for `Animation.stopProperty`). `Owner` is the type that declares `p`,
## not a subtype.
##
## The block may declare a class's own default handlers, as Kivy's class
## defines `on_e` and `on_p`: `method onE*(w: Owner; args): bool {.base.}`
## and `method onPChanged*(w: Owner; v: T) {.base.}` replace the generated
## ones (which return false and do nothing). A subclass overrides them.
##
## A wrong property, event or default name, or a callback of the wrong type,
## is a compile error.

