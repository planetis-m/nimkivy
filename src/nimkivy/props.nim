func `==`*[T: Equatable](a, b: Opt[T]): bool =
  ## Whether `a` and `b` are both none or hold equal values. std/opt has no
  ## `==`; a property of type `Opt[T]` compares with this one.
  case a
  of Some(x):
    case b
    of Some(y): result = x == y
    of None(): result = false
  of None():
    result = b.isNone

proc quitOutOfBounds*(what, value: string) =
  ## Stops the program: `value` is outside the bounds of property `what`.
  quit what & ": " & value & " is out of its bounds"

